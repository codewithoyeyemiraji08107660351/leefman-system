    public void validateFields() {
        String name = txtItemName.getText();
        String description = txtItemDescription.getText();
        String amount = txtAmount.getText();

        if (!name.equals("") && !description.equals("") && amount.matches(amountPattern)) {
            btnSubmit.setEnabled(true);
        } else {
            btnSubmit.setEnabled(false);
        }
    }

    public void getTailorLoanDetails() {
        List<LoanDetails> loansList = TailorDao.getTailorLoanDetails();
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();

        for (LoanDetails l : loansList) {
            dtm.addRow(new Object[]{
                l.getLoanId(),
                l.getTailorName(),
                l.getItemDescription(),
                l.getLoanAmount(),
                l.getRemainingBalance(),
                l.getStatus(),
                l.getLoanDate(),
                l.getLastPaymentDate(),});
        }
    }

