    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        OrderDetail detail = new OrderDetail();
        detail.setOrderId(orderId);
        detail.setSewingStyle(txtSewingStyle.getText());
        detail.setMeasurement(txtMeasurement.getText());
        detail.setItemUsed(txtItemUsed.getText());
        detail.setAccessories(txtAccessories.getText());

        orderId = OrderDao.saveOrder(detail);

        if (orderId > 0) {
            JOptionPane.showMessageDialog(this,
                    "Order Details saved successfully, Please proceed to upload Images",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);
            
            setVisible(false);
            new OrderImages(orderId, customerId).setVisible(true);
            

        } else {
            JOptionPane.showMessageDialog(this,
                    "Failed to save order details",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddActionPerformed

