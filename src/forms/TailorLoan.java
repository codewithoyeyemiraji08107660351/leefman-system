    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:

        try {
            double amount = Double.parseDouble(txtAmount.getText().trim());
            if (amount <= 0) {
                JOptionPane.showMessageDialog(this,
                        "Amount must be greater than 0",
                        "Validation Error",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }

            Loans l = new Loans();
            l.setTailorId(tailorId);
            l.setItemName(txtItemName.getText().trim());
            l.setItemDescription(txtItemDescription.getText().trim());
            l.setAmount(amount);

            boolean success = LoanDao.saveLoan(l);

            if (success) {
                clear();
                getTailorLoanDetails();
                if (getParent() instanceof Tailors) {
                    ((Tailors) getParent()).refreshLoanInfo();
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a valid numeric amount",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

